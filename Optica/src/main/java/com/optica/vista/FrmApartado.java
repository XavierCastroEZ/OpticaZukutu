    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
            int indiceCliente = cboCliente.getSelectedIndex();
    int indiceProducto = cboProducto.getSelectedIndex();

    if (indiceCliente == -1 || indiceProducto == -1 || txtFecha.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos.");
        return;
    }

    try {
        Apartado apartado = new Apartado();

        apartado.setIdCliente(listaClientes.get(indiceCliente).getIdCliente());
        apartado.setIdProducto(listaProductos.get(indiceProducto).getIdProducto());
        apartado.setFecha(java.sql.Date.valueOf(txtFecha.getText()));
        apartado.setEstado("PENDIENTE");

        ApartadoDAO dao = new ApartadoDAO();

        if (dao.insertar(apartado)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Apartado guardado correctamente.");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo guardar el apartado.");
        }

    } catch (IllegalArgumentException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "La fecha debe tener el formato yyyy-MM-dd.");
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        // TODO add your handling code here:
            int indiceCliente = cboCliente.getSelectedIndex();

    if (indiceCliente == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un cliente.");
        return;
    }

    int idCliente = listaClientes.get(indiceCliente).getIdCliente();

    ApartadoDAO dao = new ApartadoDAO();
    java.util.ArrayList<Apartado> lista = dao.listarPorCliente(idCliente);

    javax.swing.table.DefaultTableModel modelo =
        (javax.swing.table.DefaultTableModel) tblApartados.getModel();

    modelo.setRowCount(0);

    for (Apartado apartado : lista) {
        String nombreProducto = "";

        for (com.optica.modelo.Producto producto : listaProductos) {
            if (producto.getIdProducto() == apartado.getIdProducto()) {
                nombreProducto = producto.getNombre();
                break;
            }
        }

        modelo.addRow(new Object[]{
            apartado.getIdApartado(),
            cboCliente.getSelectedItem(),
            nombreProducto,
            apartado.getFecha(),
            apartado.getEstado()
        });
    }
    }//GEN-LAST:event_btnConsultarActionPerformed

