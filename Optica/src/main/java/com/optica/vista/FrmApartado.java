    public FrmApartado(int idCliente, int idProducto) {
        initComponents();
        cargarDatos(idCliente);

        for (int i = 0; i < listaProductos.size(); i++) {
            if (listaProductos.get(i).getIdProducto() == idProducto) {
                cboProducto.setSelectedIndex(i);
                break;
            }
        }

        cboCliente.setEnabled(false);
        cboProducto.setEnabled(false);
}

    private void cargarDatos(int idCliente) {
        com.optica.dao.ClienteDAO daoCliente = new com.optica.dao.ClienteDAO();
        listaClientes = new java.util.ArrayList<>();
        cboCliente.removeAllItems();

        for (com.optica.modelo.Cliente cliente : daoCliente.listar()) {
            if (cliente.getIdCliente() == idCliente) {
                listaClientes.add(cliente);
                cboCliente.addItem(cliente.getNombre());
                break;
            }
        }

        com.optica.dao.ProductoDAO daoProducto = new com.optica.dao.ProductoDAO();
        listaProductos = daoProducto.listarAros();

        cboProducto.removeAllItems();

        for (com.optica.modelo.Producto producto : listaProductos) {
            cboProducto.addItem(producto.getNombre());
        }
    }
