    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        int fila = tblApartados.getSelectedRow();

        if (fila == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un apartado de la tabla.");
            return;
        }

        int idApartado = Integer.parseInt(tblApartados.getValueAt(fila, 0).toString());

        String[] estados = {"PENDIENTE", "ENTREGADO", "CANCELADO"};

        String estado = (String) javax.swing.JOptionPane.showInputDialog(
            this,
            "Seleccione el nuevo estado:",
            "Actualizar apartado",
            javax.swing.JOptionPane.QUESTION_MESSAGE,
            null,
            estados,
            tblApartados.getValueAt(fila, 4)
        );

        if (estado == null) {
            return;
        }

        ApartadoDAO dao = new ApartadoDAO();

        if (dao.actualizarEstado(idApartado, estado)) {
            tblApartados.setValueAt(estado, fila, 4);
            javax.swing.JOptionPane.showMessageDialog(this, "Apartado actualizado correctamente.");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo actualizar el apartado.");
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

