    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
    // TODO add your handling code here:
    ClienteDAO dao = new ClienteDAO();
    java.util.List<Cliente> lista = dao.listar();

    javax.swing.table.DefaultTableModel modelo =
        (javax.swing.table.DefaultTableModel) tblClientes.getModel();

    modelo.setRowCount(0);

    for (Cliente c : lista) {
        modelo.addRow(new Object[]{
            c.getIdCliente(),
            c.getNombre(),
            c.getDni(),
            c.getTelefono(),
            c.getCorreo()
        });
}
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        String nombre = txtNombre.getText();
        String dni = txtDNI.getText();
        String telefono = txtTelefono.getText();
        String correo = txtCorreo.getText();

    if (nombre.isEmpty() || dni.isEmpty() || correo.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Complete los campos obligatorios");
    } else {
        Cliente c = new Cliente();
        c.setNombre(nombre);
        c.setDni(dni);
        c.setTelefono(telefono);
        c.setCorreo(correo);
        c.setIdUsuario(1);

        ClienteDAO dao = new ClienteDAO();

    if (dao.insertar(c)) {
        JOptionPane.showMessageDialog(this, "Cliente guardado correctamente");
        btnLimpiarActionPerformed(evt);
    } else {
        JOptionPane.showMessageDialog(this, "Error al guardar el cliente");
        }
    }//GEN-LAST:event_btnGuardarActionPerformed
}
