    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        // TODO add your handling code here:
            int indice = cboCliente.getSelectedIndex();

    if (indice == -1) {
        javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un cliente");
        return;
    }

    int idCliente = listaClientes.get(indice).getIdCliente();

    com.optica.dao.MedicionDAO dao = new com.optica.dao.MedicionDAO();
    java.util.List<com.optica.modelo.Medicion> mediciones = dao.listarPorCliente(idCliente);

    javax.swing.table.DefaultTableModel modelo =
    (javax.swing.table.DefaultTableModel) tblMediciones.getModel();
    modelo.setRowCount(0);

    for (com.optica.modelo.Medicion m : mediciones) {
        modelo.addRow(new Object[]{
            m.getIdMedicion(),
            listaClientes.get(indice).getNombre(),
            m.getFecha(),
            m.getEsfera(),
            m.getCilindro(),
            m.getEje(),
            m.getAdicion()
        });
    }
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
            try {
        int indice = cboCliente.getSelectedIndex();

        if (indice == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione un cliente");
            return;
        }

        if (txtFecha.getText().isEmpty() || txtEsfera.getText().isEmpty()
                || txtCilindro.getText().isEmpty() || txtEje.getText().isEmpty()
                || txtAdicion.getText().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Complete todos los campos");
            return;
        }

        com.optica.modelo.Medicion m = new com.optica.modelo.Medicion();

        m.setIdCliente(listaClientes.get(indice).getIdCliente());
        m.setFecha(java.sql.Date.valueOf(txtFecha.getText()));
        m.setEsfera(Double.parseDouble(txtEsfera.getText()));
        m.setCilindro(Double.parseDouble(txtCilindro.getText()));
        m.setEje(Integer.parseInt(txtEje.getText()));
        m.setAdicion(Double.parseDouble(txtAdicion.getText()));

        com.optica.dao.MedicionDAO dao = new com.optica.dao.MedicionDAO();

        if (dao.insertar(m)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Medición guardada correctamente");
            btnConsultarActionPerformed(evt);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo guardar la medición");
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Verifique los datos. La fecha debe tener formato AAAA-MM-DD.\n" + e.getMessage());
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

