    private void cargarClientes() {
    com.optica.dao.ClienteDAO dao = new com.optica.dao.ClienteDAO();
    listaClientes = dao.listar();

    cboCliente.removeAllItems();

    for (com.optica.modelo.Cliente cliente : listaClientes) {
        cboCliente.addItem(cliente.getNombre());
    }
}

