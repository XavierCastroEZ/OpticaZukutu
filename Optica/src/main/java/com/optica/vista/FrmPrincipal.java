    private void cmbModuloActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbModuloActionPerformed
    String modulo = cmbModulo.getSelectedItem().toString();

    pnlContenido.removeAll();
    pnlContenido.setLayout(new java.awt.BorderLayout());

    if (modulo.equals("Clientes")) {
        FrmCliente formulario = new FrmCliente();
        pnlContenido.add(formulario.getContentPane(), java.awt.BorderLayout.CENTER);

    } else if (modulo.equals("Inventario")) {
        FrmInventario formulario = new FrmInventario();
        pnlContenido.add(formulario.getContentPane(), java.awt.BorderLayout.CENTER);

    } else if (modulo.equals("Mediciones")) {
        FrmMedicion formulario = new FrmMedicion();
        pnlContenido.add(formulario.getContentPane(), java.awt.BorderLayout.CENTER);

    } else if (modulo.equals("Mis mediciones")) {
        FrmMedicion formulario = new FrmMedicion(idCliente);
        pnlContenido.add(formulario.getContentPane(), java.awt.BorderLayout.CENTER);

    } else if (modulo.equals("Apartados")) {
        FrmApartado formulario = new FrmApartado(idCliente);
        pnlContenido.add(formulario.getContentPane(), java.awt.BorderLayout.CENTER);

    } else if (modulo.equals("Ventas")) {
        FrmVenta formulario = new FrmVenta(idUsuario);
        pnlContenido.add(formulario.getContentPane(), java.awt.BorderLayout.CENTER);
    }else if (modulo.equals("Catálogo")) {
    
    FrmInventario formulario = new FrmInventario(true, idCliente);
    pnlContenido.add(formulario.getContentPane(), java.awt.BorderLayout.CENTER);

    pnlContenido.revalidate();
    pnlContenido.repaint();
    }
    }//GEN-LAST:event_cmbModuloActionPerformed

