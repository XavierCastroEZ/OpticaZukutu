        private void cargarClientes() {
            ClienteDAO dao = new ClienteDAO();
            listaClientes = dao.listar();

            cboCliente.removeAllItems();

            for (Cliente c : listaClientes) {
                cboCliente.addItem(c.getNombre());
            }
        }

private void cargarProductos() {
    ProductoDAO dao = new ProductoDAO();
    listaProductos = dao.listar();

    cboProducto.removeAllItems();

    for (Producto p : listaProductos) {
        cboProducto.addItem(p.getNombre());
    }
}

private void mostrarPrecio() {
    int indice = cboProducto.getSelectedIndex();

    if (indice >= 0 && indice < listaProductos.size()) {
        Producto p = listaProductos.get(indice);
        txtPrecio.setText(String.valueOf(p.getPrecio()));

        int cantidad = 1;
        txtCantidad.setText(String.valueOf(cantidad));
        txtSubtotal.setText(String.valueOf(p.getPrecio() * cantidad));
    }
}

