    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        // TODO add your handling code here:
    if (cboCliente.getSelectedIndex() < 0) {
        JOptionPane.showMessageDialog(this, "Seleccione un cliente");
        return;
    }

    Cliente cliente = listaClientes.get(cboCliente.getSelectedIndex());

    VentaDAO ventaDAO = new VentaDAO();
    ArrayList<Object[]> detalles = ventaDAO.consultarVentas(cliente.getIdCliente());

    modelo.setRowCount(0);

    for (Object[] detalle : detalles) {
        modelo.addRow(detalle);
    }

    calcularTotal();

    if (detalles.isEmpty()) {
        JOptionPane.showMessageDialog(this, "El cliente no tiene ventas registradas");
    }
    }//GEN-LAST:event_btnConsultarActionPerformed
private void calcularTotal() {
    double subtotal = 0;

    for (int i = 0; i < modelo.getRowCount(); i++) {
        subtotal += Double.parseDouble(modelo.getValueAt(i, 4).toString());
    }

    double impuesto = subtotal * 0.15;
    double total = subtotal + impuesto;

    txtTotal.setText(String.valueOf(total));
}
