    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        // TODO add your handling code here:
        int indice = cboProducto.getSelectedIndex();

        if (indice < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un producto");
            return;
        }

        Producto p = listaProductos.get(indice);

        int cantidad = Integer.parseInt(txtCantidad.getText());

        if (cantidad <= 0 || cantidad > p.getStock()) {
            JOptionPane.showMessageDialog(this, "Cantidad no válida o stock insuficiente");
            return;
        }

        double subtotal = p.getPrecio() * cantidad;

        modelo.addRow(new Object[]{
            p.getIdProducto(),
            p.getNombre(),
            cantidad,
            p.getPrecio(),
            subtotal
        });

        calcularTotal();
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
    if (cboCliente.getSelectedIndex() < 0) {
        JOptionPane.showMessageDialog(this, "Seleccione un cliente");
        return;
    }

    if (modelo.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this, "Agregue productos a la venta");
        return;
    }

    try {
        Cliente cliente = listaClientes.get(cboCliente.getSelectedIndex());

        Venta venta = new Venta();
        venta.setIdCliente(cliente.getIdCliente());
        venta.setIdUsuario(idUsuario);
        venta.setFecha(java.sql.Date.valueOf(txtFecha.getText()));

        com.optica.dao.MedicionDAO medicionDAO = new com.optica.dao.MedicionDAO();

        java.util.ArrayList<com.optica.modelo.Medicion> mediciones
                = medicionDAO.listarPorCliente(cliente.getIdCliente());

        if (mediciones.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "El cliente no tiene mediciones registradas");
            return;
        }

        String[] opciones = new String[mediciones.size()];

        for (int i = 0; i < mediciones.size(); i++) {
            com.optica.modelo.Medicion m = mediciones.get(i);

            opciones[i] = "Fecha: " + m.getFecha()
                    + " | Esfera: " + m.getEsfera()
                    + " | Cilindro: " + m.getCilindro()
                    + " | Eje: " + m.getEje()
                    + " | Adición: " + m.getAdicion()
                    + " | ID: " + m.getIdMedicion();
        }

        String seleccion = (String) JOptionPane.showInputDialog(
                this,
                "Seleccione la medición que desea asociar a la venta:",
                "Seleccionar medición",
                JOptionPane.QUESTION_MESSAGE,
                null,
                opciones,
                opciones[0]
        );

        if (seleccion == null) {
            return;
        }

        int indiceMedicion = java.util.Arrays.asList(opciones).indexOf(seleccion);

        venta.setIdMedicion(mediciones.get(indiceMedicion).getIdMedicion());

        ArrayList<Object[]> detalles = new ArrayList<>();

        for (int i = 0; i < modelo.getRowCount(); i++) {
            detalles.add(new Object[]{
                modelo.getValueAt(i, 0),
                modelo.getValueAt(i, 1),
                modelo.getValueAt(i, 2),
                modelo.getValueAt(i, 3),
                modelo.getValueAt(i, 4)
            });
        }

        VentaDAO ventaDAO = new VentaDAO();

        if (ventaDAO.registrarVenta(venta, detalles)) {
            JOptionPane.showMessageDialog(this, "Venta registrada correctamente");
            modelo.setRowCount(0);
            calcularTotal();
        } else {
            JOptionPane.showMessageDialog(this,
                    "No se pudo registrar la venta. Verifique el stock y las mediciones del cliente.");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Error al registrar la venta: " + e.getMessage());
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

